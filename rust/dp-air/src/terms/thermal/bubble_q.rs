//! Профиль «между» `q(ξ)`, ξ = z/z_l ∈ [0, 1] (TB1 v5 `bubble.between_q`): средний по жизни поток вверх шаблона
//! (`from_game_strength`) по высоте, среднее по ξ (трапеции) = 1; 21 узлов, линейно между узлами
//! (`round3/between.py`, TB-12 на v5).

/// Узлы `q` при ξ = `i / (N − 1)`.
#[rustfmt::skip]
const Q: [f64; 21] = [
    0.0, 0.44752177774714036, 0.6993158433474265,
    0.8612045799163561, 0.9903752896003891, 1.1005690914326385,
    1.1955613537459822, 1.2918692699459584, 1.3412936555374746,
    1.362374318722942, 1.3960947044475158, 1.4115065216280567,
    1.3845375229406574, 1.3411277867302769, 1.273907268809101,
    1.1484386629963692, 0.9807275423890559, 0.7836072430932367,
    0.6236477158461969, 0.365879671545737, 0.0008803591549801406,
];

/// `q(ξ)`: линейно между узлами, вне `[0, 1]` — край.
pub fn between_q(xi: f64) -> f64 {
    let n = Q.len() - 1;
    let f = xi.clamp(0.0, 1.0) * n as f64;
    let i = (f as usize).min(n - 1);
    Q[i] + (f - i as f64) * (Q[i + 1] - Q[i])
}

/// Среднее `q` по ξ (трапеции по узлам).
pub fn mean() -> f64 {
    let n = Q.len() - 1;
    Q.windows(2).map(|w| 0.5 * (w[0] + w[1])).sum::<f64>() / n as f64
}

/// Узлы таблицы (для тестов).
pub fn nodes() -> &'static [f64] {
    &Q
}
