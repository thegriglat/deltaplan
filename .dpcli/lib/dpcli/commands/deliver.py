"""deliver — сдача модуля: squash ветки модуля в итоговую ветку, журнал остаётся в ветке модуля (и под архивным тегом),
в итоговую ветку из <plan_dir>/<модуль>/ попадают только md для людей: решения и вопросы, сводка реализации.

  deliver <модуль> [--into ВЕТКА] [-m ТЕКСТ] [--force] [--dry]   squash ветки модуля в копию ВЕТКИ, коммит, архивный тег
  deliver <модуль> --in-place [--dry]                              журнал модуля уже в текущей ветке: свернуть его в md
  deliver <модуль> --rerender [--from REF] [--area A]              пересобрать md сданного модуля из журнала в REF (архивный тег)

После сдачи план и контракты модуля получают status: closed, INDEX.md пересобирается (docs index).
"""
import json
import re
import io
import shutil
import subprocess
import tarfile
from pathlib import Path

from .. import config, gitx
from ..journal import (FINAL, add_event, all_modules, by_default, check_area, guard_main, journal_commit, module_base,
                       module_meta, task_cards, task_states)
from ..util import CLI, DpError, now, pretty, read_json, read_jsonl, session_line

GEN = "<!-- generated by dpcli deliver; не править руками -->"
WHO = {"user": "пользователь", "coordinator": "координатор", "main": "главная сессия", "executor": "исполнитель"}


def keep_files():
    return list(config.get("deliver.keep") or ["decisions.md", "summary.md"])


def archive_tag(mod):
    t = config.get("deliver.archive_tag", "archive/{module}")
    return config.subst(t, module=mod) if t else None


def resolve_generated(root, files):
    from .docs import resolve_generated as rg
    return rg(root, files)


def fm(mod, summary, area=None, archive=None):
    from .docs import dump_fm  # тот же формат frontmatter, что проверяет docs check
    d = {"type": "journal", "status": "closed", "module": mod}
    if area:
        d["area"] = area
    d.update({"updated": now()[:10], "summary": summary, "related": [f"{config.plan_dir()}/{mod}.md"]})
    if archive:
        d["archive"] = archive
    d["generated"] = True
    return dump_fm(d) + GEN + "\n"


def task_order(cards, st):
    """ID задач в естественном порядке: PP-2 раньше PP-10."""
    ids = list(dict.fromkeys(list(cards) + list(st)))
    return sorted(ids, key=lambda t: [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", t)])


def day(t):
    """Дата записи журнала ГГГГ-ММ-ДД: время через полгода никому не нужно."""
    return t[:10] if t and len(t) >= 10 else ""


APPROVED = "утверждено разработчиком"
# «почему», которое называет только источник («ответ пользователя 2026-10-09»), — не причина
SOURCE_ONLY = re.compile(r"(?:(?:уточнени[ея]|указани[ея]|ответы?|постановка|сообщени[ея]|требовани[ея]|разрешение|правило"
                         r"|исправление|решени[ея]|приёмка)(?: на вопрос)?(?: пользователя)?|пользователь)(?: \d{4}-\d{2}-\d{2})?",
                         re.I)


def why_of(d):
    """Причина решения для людей: у решения пользователя без причины (или с одной ссылкой на источник) —
    «утверждено разработчиком»; остальное — как записано."""
    w = one(d.get("why") or "")
    if d.get("by") == "user" and (not w or SOURCE_ONLY.fullmatch(w)):
        return APPROVED
    return w


def one(s):
    return " ".join(str(s).split())


def item(x):
    """Пункт отчёта: строка или объект (uncertain: where/why/checked) → одна строка."""
    if isinstance(x, dict):
        parts = [f"`{x['where']}`" if x.get("where") else ""] + [one(x[k]) for k in ("why", "what", "text") if x.get(k)]
        if x.get("checked"):
            parts.append(f"проверено: {one(x['checked'])}")
        rest = {k: v for k, v in x.items() if k not in ("where", "why", "what", "text", "checked")}
        if rest:
            parts.append(one(json.dumps(rest, ensure_ascii=False)))
        return " — ".join(p for p in parts if p)
    return one(x)


def render_decisions(mod, home, area=None, archive=None):
    """Вопросы с ответами и решения — для людей; ответ на вопрос стоит под вопросом, а не среди решений."""
    decs = read_jsonl(home / "decisions.jsonl")
    answers = {}
    for d in decs:
        if d.get("answers"):
            answers.setdefault(d["answers"], []).append(d)
    qs = [d for d in decs if d.get("kind") == "question"]
    plain = [d for d in decs if d.get("kind") != "question" and not d.get("answers")]
    L = [f"# {mod} — решения и вопросы", "",
         f"План — `{config.plan_dir()}/{mod}.md`. Решения — кто и почему выбрал вариант; вопросы — развилки, "
         f"на которых работа останавливалась до ответа."
         + (f" Полный журнал (карточки, отчёты, события) — в git: `{archive}`." if archive else ""), ""]
    L += ["## Вопросы и ответы", ""]
    for q in qs:
        L.append(f"### {q.get('id', '?')} — {day(q.get('t', ''))}, спросил {WHO.get(q.get('by'), q.get('by', '-'))}")
        L += ["", one(q.get("text", "")), ""]
        if q.get("why"):
            L += [f"Контекст: {one(q['why'])}", ""]
        for a in answers.get(q.get("id"), []):
            L.append(f"**Ответ** ({WHO.get(a.get('by'), a.get('by', '-'))}, {day(a.get('t', ''))}): {one(a.get('text', ''))}"
                     + (f" Почему: {one(a['why'])}" if a.get("why") and not SOURCE_ONLY.fullmatch(one(a["why"])) else ""))
            L.append("")
        if not answers.get(q.get("id")):
            L += ["**Ответа нет.**", ""]
    if not qs:
        L += ["Вопросов не было.", ""]
    L += ["## Решения", ""]
    for by in ("user", "main", "coordinator", "executor"):
        rows = [d for d in plain if d.get("by") == by]
        if not rows:
            continue
        L += [f"### Решения: {WHO[by]}", ""]
        for d in rows:
            w = why_of(d)
            L.append(f"- {day(d.get('t', ''))} — {one(d.get('text', ''))}" + (f" *Почему:* {w}" if w else ""))
        L.append("")
    other = [d for d in plain if d.get("by") not in WHO]
    for d in other:
        w = why_of(d)
        L.append(f"- {day(d.get('t', ''))} ({d.get('by', '-')}) — {one(d.get('text', ''))}" + (f" *Почему:* {w}" if w else ""))
    if not plain:
        L.append("Решений не записано.")
    n_ans = sum(1 for q in qs if answers.get(q.get("id")))
    summ = f"Решения ({len(plain)}) и вопросы ({len(qs)}, отвечено {n_ans}) модуля {mod}"
    return fm(mod, summ, area, archive) + "\n" + "\n".join(L).rstrip() + "\n"


def render_summary(mod, home, area=None, archive=None):
    """Сводка реализации: задача, итог, что не сделано, в чём исполнитель не уверен, его вопросы, вердикт ревью."""
    cards = task_cards(home)
    st = task_states(home)
    tasks = home / "tasks"
    L = [f"# {mod} — сводка реализации", "",
         f"По задачам модуля: итог исполнителя, что не сделано, где он не уверен. План — `{config.plan_dir()}/{mod}.md`, "
         f"решения — `decisions.md`.", "", "## Задачи", ""]
    open_ = []
    order = task_order(cards, st)
    for tid in order:
        c = cards.get(tid) or {}
        s = st.get(tid, {"status": "created"})
        status = "влита" if "merged" in s.get("seen", set()) else s["status"]
        if s["status"] not in FINAL:
            open_.append(tid)
        r = read_json(tasks / f"{tid}.report.json") or {}
        rv = read_json(tasks / f"{tid}.review.json") or {}
        L += [f"### {tid} — {one(c.get('title', ''))}", ""]
        meta = f"Статус: **{status}**"
        if rv.get("verdict"):
            meta += f"; ревью: {rv['verdict']}"
        L += [meta, ""]
        if r.get("summary"):
            L += [one(r["summary"]), ""]
        elif s.get("note"):
            L += [one(s["note"]), ""]
        for key, title in (("not_done", "Не сделано"), ("uncertain", "Не уверен"), ("questions", "Вопросы исполнителя")):
            vals = [v for v in r.get(key) or [] if v]
            if vals:
                L.append(f"{title}:")
                L += [f"- {item(v)}" for v in vals]
                L.append("")
    if not order:
        L += ["Задач нет.", ""]
    summ = f"Сводка реализации модуля {mod}: {len(order)} задач, итоги и оговорки исполнителей"
    return fm(mod, summ, area, archive) + "\n" + "\n".join(L).rstrip() + "\n", open_


def write_md(mod, home, dest, area=None, archive=None):
    """decisions.md и summary.md из журнала home в каталог dest. → (пути, незакрытые задачи)."""
    dest.mkdir(parents=True, exist_ok=True)
    summary, open_ = render_summary(mod, home, area, archive)
    files = {"decisions.md": render_decisions(mod, home, area, archive), "summary.md": summary}
    out = []
    for name in keep_files():
        if name in files:
            (dest / name).write_text(files[name], encoding="utf-8")
            out.append(dest / name)
    return out, open_


def drop_journal(cwd, rel_dir, keep):
    """Из индекса и с диска — всё в rel_dir, кроме keep (имена файлов в корне rel_dir)."""
    d = Path(cwd) / rel_dir
    tracked = [f for f in gitx.gitr("-c", "core.quotepath=off", "ls-files", "-z", "--", rel_dir, cwd=cwd).stdout.split("\0") if f]
    gone = [f for f in tracked if f not in {f"{rel_dir}/{k}" for k in keep}]
    if gone:
        r = gitx.gitr("rm", "-q", "-f", "--", *gone, cwd=cwd)
        if r.returncode:
            raise DpError(f"git rm: {gitx.gerr(r)}")
    if d.is_dir():
        for p in d.iterdir():
            if p.name not in keep:
                shutil.rmtree(p) if p.is_dir() else p.unlink()
    return gone


FM_LINE = re.compile(r"^(\w+):")


def set_fm(text, **vals):
    """Поменять/добавить ключи frontmatter построчно, не трогая остальной формат (YAML-списки, кавычки)."""
    if not text.startswith("---\n") or text.find("\n---", 4) < 0:
        return None
    end = text.find("\n---", 4)
    lines = text[4:end].split("\n")
    quoted = any(re.match(r'^\w+: "', l) for l in lines)  # стиль файла: JSON-строки или голый YAML
    for k, v in vals.items():
        val = json.dumps(v, ensure_ascii=False) if quoted or not re.fullmatch(r"[\w.-]+", str(v)) else str(v)
        idx = next((i for i, l in enumerate(lines) if (m := FM_LINE.match(l)) and m[1] == k), None)
        if idx is not None:
            lines[idx] = f"{k}: {val}"
            continue
        after = {"area": "module"}.get(k)
        pos = next((i + 1 for i, l in enumerate(lines) if (m := FM_LINE.match(l)) and m[1] == after), len(lines))
        lines.insert(pos, f"{k}: {val}")
    return "---\n" + "\n".join(lines) + text[end:]


def close_docs(root, mod, area, day=None):
    """План модуля и его контракты (module во frontmatter) → status: closed, updated (day или сегодня), area. → пути от корня."""
    from .docs import split_fm
    root = Path(root)
    cands = [root / config.plan_dir() / f"{mod}.md"]
    cdir = root / config.contracts_dir()
    if cdir.is_dir():
        for p in sorted(cdir.glob("*.md")):
            if p not in cands and (split_fm(p.read_text(encoding="utf-8"))[0] or {}).get("module") == mod:
                cands.append(p)
    out = []
    for p in cands:
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8")
        f = split_fm(text)[0]
        if f is None:
            continue
        vals = {"status": "closed"}
        if area and f.get("area") != area:
            vals["area"] = area
        if f.get("status") == "closed" and "area" not in vals:
            continue
        vals["updated"] = day or now()[:10]
        p.write_text(set_fm(text, **vals), encoding="utf-8")
        out.append(p.relative_to(root).as_posix())
    return out


def reindex(root):
    """docs index в копии root → изменённые пути от корня (INDEX.md, реестры); нет каталога документов — []."""
    from .docs import Ctx, cmd_index
    x = Ctx(root)
    if not x.docs.is_dir():
        return []
    cmd_index(x, None)
    return [x.index_path, x.reg]


def finish(root, mod, area):
    """После сдачи: закрыть план и контракты, пересобрать индекс, всё в индекс git."""
    paths = close_docs(root, mod, area) + reindex(root)
    if paths:
        gitx.gitr("add", "--", *paths, cwd=root)
    return paths


def journal_from(ref, rel_dir, dest):
    """Каталог журнала rel_dir из коммита/тега ref → dest/rel_dir (git archive, без checkout)."""
    r = subprocess.run(["git", "archive", "--format=tar", ref, "--", rel_dir], cwd=gitx.toplevel(), capture_output=True)
    if r.returncode:
        raise DpError(f"нет журнала {rel_dir} в {ref}: {r.stderr.decode(errors='replace').strip()}")
    shutil.rmtree(dest, ignore_errors=True)
    with tarfile.open(fileobj=io.BytesIO(r.stdout)) as t:
        try:
            t.extractall(dest, filter="data")
        except TypeError:  # Python < 3.12: без filter; архив — наш собственный журнал из git
            t.extractall(dest)
    return dest / rel_dir


def cmd_rerender(a, rel_dir):
    """md сданного модуля заново из архивного журнала: формат поменялся — файлы «не править руками» не правим руками."""
    ref = a.from_ or archive_tag(a.module)
    if not ref:
        raise DpError("нужен --from: тег или коммит с журналом модуля (deliver.archive_tag не задан)")
    top = gitx.toplevel()
    tmp = top / "build" / "dpcli" / f"rerender-{a.module}"
    home = journal_from(ref, rel_dir, tmp)
    if not (home / "events.jsonl").exists() and not (home / "module.json").exists():
        raise DpError(f"в {ref}:{rel_dir} нет журнала dpcli")
    area = a.area or module_meta(a.module, home).get("area")
    check_area(area)
    if a.dry:
        print(f"{a.module}: {', '.join(keep_files())} из {ref}, area {area or '-'}; план и контракты → closed")
        shutil.rmtree(tmp, ignore_errors=True)
        return
    # ссылка на журнал в md — только если архивные теги включены: иначе ref есть лишь в этой копии
    made, _ = write_md(a.module, home, top / rel_dir, area, ref if archive_tag(a.module) else None)
    last = max((str(e.get("t", "")) for e in read_jsonl(home / "events.jsonl")), default="")[:10] or None
    shutil.rmtree(tmp, ignore_errors=True)
    closed = close_docs(top, a.module, area, last)  # дата закрытия — последняя запись журнала, не день пересборки
    reindex(top)
    print(f"{a.module}: {', '.join(p.name for p in made)} из {ref}" + (f"; закрыты {', '.join(closed)}" if closed else "")
          + "; INDEX.md пересобран; не закоммичено")


def commit(cwd, msg, body):
    args = ["commit", "-q", "-m", msg] + (["-m", body] if body else []) + (["-m", session_line()] if session_line() else [])
    r = subprocess.run(["git", *args], cwd=cwd, text=True)  # хуки (pre-commit) — с выводом в терминал
    if r.returncode:
        raise DpError(f"git commit не прошёл (код {r.returncode}); изменения оставлены в индексе {pretty(cwd)} — "
                      f"поправить и закоммитить руками или откатить `git reset --merge`")
    return gitx.gitr("rev-parse", "--short", "HEAD", cwd=cwd).stdout.strip()


def body_text(mod, home):
    st = task_states(home)
    cards = task_cards(home)
    lines = []
    for tid in task_order(cards, st):
        if st.get(tid, {}).get("status") == "cancelled":
            continue
        lines.append(f"- {tid}: {one((cards.get(tid) or {}).get('title', ''))}")
    return "\n".join(lines)


def plan_title(mod):
    p = gitx.toplevel() / config.plan_dir() / f"{mod}.md"
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    return mod


def cmd_deliver(a):
    pd = config.plan_dir()
    rel_dir = f"{pd}/{a.module}"
    keep = keep_files()
    by = by_default(a)
    if a.rerender:
        return cmd_rerender(a, rel_dir)
    if a.in_place:
        top = gitx.toplevel()
        home = top / rel_dir
        if not (home / "events.jsonl").exists() and not (home / "module.json").exists():
            raise DpError(f"в {rel_dir} нет журнала dpcli")
        if gitx.dirty(top):
            raise DpError(f"копия {pretty(top)} грязная — сначала закоммитить или убрать изменения")
        if a.dry:
            print(f"{rel_dir}: останутся {', '.join(keep)}; удалятся {len(gitx.git('ls-files', '--', rel_dir).splitlines())} файлов журнала")
            return
        tmp = top / "build" / "dpcli" / f"deliver-{a.module}"
        area = module_meta(a.module, home).get("area")
        check_area(area)
        archive = gitx.gitr("rev-parse", "--short", "HEAD", cwd=top).stdout.strip()  # последний коммит с журналом
        made, _ = write_md(a.module, home, tmp, area, archive if archive_tag(a.module) else None)
        drop_journal(top, rel_dir, keep)
        home.mkdir(parents=True, exist_ok=True)
        for p in made:
            shutil.move(str(p), home / p.name)
        shutil.rmtree(tmp, ignore_errors=True)
        gitx.gitr("add", "--", *[f"{rel_dir}/{p.name}" for p in made], cwd=top)
        finish(top, a.module, area)
        h = commit(top, f"{a.module}: журнал dpcli свёрнут в {', '.join(p.name for p in made)}", "")
        print(f"{a.module}: {h}, в {rel_dir} оставлены {', '.join(p.name for p in made)}")
        return

    mods = all_modules()
    if a.module not in mods:
        raise DpError(f"модуль {a.module} не найден")
    home = mods[a.module]
    meta = module_meta(a.module, home)
    br = meta["branch"]
    check_area(meta.get("area"))
    into = a.into or module_base(meta)
    guard_main(into, bool(a.into), meta.get("base"))
    if br == into:
        raise DpError(f"ветка модуля {br} совпадает с итоговой")
    target = gitx.copy_of(into)
    if not target:
        raise DpError(f"ветка {into} нигде не выписана — нужна копия, где она открыта")
    st = task_states(home)
    open_ = [t for t in list(task_cards(home)) if st.get(t, {}).get("status") not in FINAL]
    from ..journal import open_questions
    oq = [q.get("id") for q in open_questions(home)]
    if (open_ or oq) and not a.force:
        raise DpError("модуль не закрыт: " + "; ".join(x for x in (
            f"задачи не приняты: {', '.join(open_)}" if open_ else "", f"вопросы без ответа: {', '.join(oq)}" if oq else "") if x)
            + " (--force — сдать как есть)")
    mcopy = gitx.copy_of(br)
    tag = archive_tag(a.module)
    if a.dry:
        print(f"{br} → {into} ({pretty(target)}): squash, из {rel_dir} останутся {', '.join(keep)}"
              + (f"; тег {tag}" if tag else ""))
        return
    if mcopy:
        jm = journal_commit(mcopy)
        if jm:
            print(f"журнал dpcli закоммичен в {pretty(mcopy)}")
        if gitx.dirty(mcopy):
            raise DpError(f"копия модуля {pretty(mcopy)} грязная — незакоммиченное не попадёт в сдачу")
    if gitx.dirty(target):
        raise DpError(f"копия {pretty(target)} грязная — отказ")
    r = gitx.gitr("merge", "--squash", br, cwd=target)
    files = [f for f in gitx.gitr("-c", "core.quotepath=off", "diff", "--name-only", "-z", "--diff-filter=U",
                                  cwd=target).stdout.split("\0") if f] if r.returncode else []
    if r.returncode and not (files and resolve_generated(target, files)):  # индексы всё равно пересоберёт finish
        gitx.gitr("reset", "--merge", cwd=target)
        raise DpError(f"конфликт squash {br} в {into}, отменено; файлы: {', '.join(files) or gitx.gerr(r)}"
                      f" — сначала `{CLI} sync {a.module}`")
    drop_journal(target, rel_dir, keep)
    made, _ = write_md(a.module, home, target / rel_dir, meta.get("area"), tag)
    gitx.gitr("add", "--", *[str(p) for p in made], cwd=target)
    finish(target, a.module, meta.get("area"))
    if not gitx.gitr("diff", "--cached", "--quiet", cwd=target).returncode:
        print(f"{into}: изменений нет — {br} уже сдана")
        return
    title = a.message or f"{a.module}: {plan_title(a.module)}"
    h = commit(target, title if len(title) <= 72 else title[:71] + "…", body_text(a.module, home))
    add_event(home, None, "delivered", by, note=f"squash в {into}: {h}", commits=[h])
    if mcopy:
        journal_commit(mcopy)
    out = f"{into} {h}: squash {br}, журнал → {', '.join(p.name for p in made)}"
    if tag:
        r = gitx.gitr("tag", "-f", tag, br)
        out += f"; тег {tag}" if not r.returncode else f"; тег не поставлен: {gitx.gerr(r)}"
    print(out + f". Ветку {br} больше не развивать: доработка — новый модуль или задача от {into}")


def register(sp):
    q = sp.add_parser("deliver", help="сдать модуль: squash в итоговую ветку, журнал → decisions.md и summary.md")
    q.add_argument("module")
    q.add_argument("--into", metavar="ВЕТКА", help="итоговая ветка (по умолчанию база модуля — фичеветка, от которой он заведён)")
