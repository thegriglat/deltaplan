"""Теоретический градиент Td в хорошо перемешанном слое (постоянное отношение смеси, давление падает с высотой
по гидростатике и T по сухой адиабате): dTd/dz при Магнусе-Бугеру. Результат печатается (К/км)."""
import numpy as np
g, cp, Rd, Rv, L = 9.80665, 1004.0, 287.04, 461.5, 2.5e6
def td_lapse(T_c, Td_c, p=900e2):
    T = T_c + 273.15; Td = Td_c + 273.15
    dT_dz = -g / cp
    dp_dz = -p * g / (Rd * T)
    # e = w p/(0.622+w): ln e ~ ln p при постоянном w; Клаузиус-Клапейрон: dln e/dTd = L/(Rv Td^2)
    dlne_dz = dp_dz / p
    return dlne_dz * Rv * Td ** 2 / L * 1000
for T, Td in [(-15, -19), (0, -3), (15, 5), (25, 9), (30, 20)]:
    print(f"T {T:>3} Td {Td:>3} -> {td_lapse(T, Td):.2f} К/км")
