"""Общая схема решателя для всех случаев калибровки (контракт C10 v2, docs/contracts/air-model.md).

Физические параметры калибруются только на одной схеме: всё, что ниже, у Askervein и Perdigão (и любого нового
случая) одинаково. Различаться между случаями могут только входы из данных (рельеф, лес, широта, ветер,
устойчивость) и параметры, которые подгоняются у каждого случая свои (α, z0) — модуль случая описывает их в SETUP.
Прогоны для оценки ошибки схемы (1-й порядок игры, мельче сетка) помечаются в строке `scheme_ctl: true`
и в χ² не входят.

Правка этого файла = новая версия C10 (через координатора).
"""
from __future__ import annotations

# Схема и замыкание (А3: hb, local_k вкл, cbl; А1: Pr_t 0,85; А2: k_relax 0,1). Перенос — 2-й порядок без
# ограничителя: ближе к сошедшемуся по сетке решению, ошибка 1-го порядка игры — отдельная систематика.
SCHEME = dict(
    adv2=True,
    limiter=0,
    closure="hb",
    local_k=True,
    heat_mode="cbl",
    pr_t=0.85,
    k_relax=0.1,
    cs_h=0.25,
    k_fa=1.0,
)
MAX_OUTER = 4000          # предел внешних итераций; критерий остановки — air.py по умолчанию
NEUTRAL = True            # оба случая — нейтраль: dθ̄/dz = 0, без нагрева (устойчивость — в SETUP случая)

# Поля SETUP модуля случая (для таблицы сопоставимости «настройка → случай»): числа и правила, по которым они
# получены. Геометрия задаётся правилами относительно высоты рельефа H, а не подбирается у случая отдельно.
SETUP_KEYS = (
    "H_m",               # характерная высота рельефа (гребень − основание / дно), м
    "dx_m", "dz_m",      # шаг сетки; dz = dx/2
    "L_dom_m",           # сторона области
    "top_m",             # потолок над нижней точкой рельефа
    "sponge_side_m", "sponge_top_m",
    "f_cor",             # параметр Кориолиса по широте места, 1/с
    "wdir_deg", "u_ref",  # ветер «откуда» и опорная скорость (как задана: мачта, высота)
    "alpha", "z0_m",     # номинал случая (подгоняются у случая)
    "z_sat_rule", "max_profile",   # насыщение степенного профиля притока: одно правило для всех случаев
    "canopy",            # лес: смещение d и доля; нет леса — d = 0
    "stability",         # что в данных (z/L, Ri) и как задано в модели
)


def apply(params: dict, ctl: bool = False) -> dict:
    """Параметры прогона случая с общей схемой поверх. ctl=True — контрольный прогон схемы (разрешает
    переопределить SCHEME, строка помечается scheme_ctl)."""
    out = dict(params)
    if not ctl:
        out.update(SCHEME)
    else:
        for k, v in SCHEME.items():
            out.setdefault(k, v)
    return out
